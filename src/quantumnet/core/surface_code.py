"""Rotated surface code: lattice, syndrome-extraction schedule, decoding.

STATUS
------
**Verified against ``stim``, at d = 3, 5, 7 and 9:**

* the **lattice** -- data sites, ancilla sites, and every X/Z role assignment
  match the reference layout exactly;
* the **CNOT layer rule** reproduces the reference circuit gate for gate, in
  every layer, for every ancilla, at d = 3, 5, 7, 9 and 11.

Both are re-derived from ``stim`` by the test suite when it is installed, so
drift fails loudly.  ``stim`` is a development-time oracle, not a dependency.

**Bounded, not general.**  ``VERIFIED_SITES`` pins the layout for the four
distances above, and a distance without a verified layout is refused rather
than generated by a formula nobody has checked.  That is not laziness: five
attempts to *derive* the boundary rule produced lattices with the correct
*counts* and the wrong *sites*, which passes a qubit-count test and is therefore
the worst available failure mode.  Pinning verified data is the honest option.

**The decoder is exact within a bound.**  :class:`MWPMDecoder` enumerates perfect
matchings, so it is exact but factorial in the detection-event count; it raises
rather than silently approximating when the instance is too large.
:func:`greedy_match` remains available for larger instances and is honestly
labelled as worse.

The layer rule
--------------
Each ancilla has up to four data neighbours at offsets ``(±1, ±1)``.  The CNOT
layer in which each is visited is fixed by the offset::

    X-type (CNOT controls):   (1,1) -> (-1,1) -> (1,-1) -> (-1,-1)
    Z-type (CNOT targets):    (1,1) -> (1,-1) -> (-1,1) -> (-1,-1)

An ancilla has no gate in a layer whose offset does not exist for it, which
is how a weight-2 boundary check ends up using layers 2 and 3 rather than 0 and
1.  Getting that wrong -- consuming slots in order of *available* neighbours --
displaced the boundary checks and mismatched the schedule.  The two orders are
perpendicular in the sense that matters: a hook residual cannot run parallel to
the logical operator whose distance it could shorten.
"""

